CREATE INDEX IX_INVENTORY_IMAGES_INV   ON INVENTORY_IMAGES (INVENTORY_ID);
CREATE INDEX IX_INVENTORY_COMPONENT   ON INVENTORY (COMPONENT_ID);
CREATE INDEX IX_SERVICES_WORKSHOP     ON SERVICES (WORKSHOP_ID);
CREATE INDEX IX_FEES_SERVICE          ON FEES (SERVICE_ID);
CREATE INDEX IX_AFFILIATIONS_SUPPLIER ON AFFILIATIONS (SUPPLIER_ID);
CREATE INDEX IX_AFFILIATIONS_WORKSHOP ON AFFILIATIONS (WORKSHOP_ID);
