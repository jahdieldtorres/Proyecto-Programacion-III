BEGIN
    FOR t IN (SELECT table_name FROM user_tables
              WHERE table_name IN ('PRICE_HISTORY', 'ORDER_ITEMS', 'ORDERS',
                                   'INVENTORY_IMAGES', 'INVENTORY', 'COMPATIBILITY',
                                   'MOTORCYCLES', 'CARS', 'VEHICLES',
                                   'COMPONENT_IMAGES', 'TRANSMISSIONS', 'ENGINES',
                                   'RIMS', 'TIRES', 'COMPONENTS',
                                   'AFFILIATIONS', 'FEES', 'SERVICES',
                                   'WORKSHOPS', 'SUPPLIERS', 'PARTNERS',
                                   'USER_ADDRESSES', 'NEIGHBORHOODS',
                                   'MUNICIPALITIES', 'DEPARTMENTS',
                                   'USERS', 'CATEGORIES', 'BRANDS'))
    LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ---------------------------------------------------------------------
-- 1. Catálogo base
-- ---------------------------------------------------------------------
CREATE TABLE BRANDS (
    ID    NUMBER GENERATED ALWAYS AS IDENTITY,
    NAME  VARCHAR2(60) NOT NULL,
    CONSTRAINT PK_BRANDS PRIMARY KEY (ID),
    CONSTRAINT UQ_BRANDS_NAME UNIQUE (NAME)
);

CREATE TABLE CATEGORIES (
    ID          NUMBER GENERATED ALWAYS AS IDENTITY,
    NAME        VARCHAR2(60) NOT NULL,
    IMAGE_FILE  VARCHAR2(120),
    CONSTRAINT PK_CATEGORIES PRIMARY KEY (ID),
    CONSTRAINT UQ_CATEGORIES_NAME UNIQUE (NAME)
);

-- ---------------------------------------------------------------------
-- 2. Usuarios y ubicación
--    Solo hay dos roles: los proveedores y talleres NO inician sesión.
-- ---------------------------------------------------------------------
CREATE TABLE USERS (
    ID                 NUMBER GENERATED ALWAYS AS IDENTITY,
    NAME               VARCHAR2(80)  NOT NULL,
    EMAIL              VARCHAR2(120) NOT NULL,
    PASSWORD_HASH      VARCHAR2(64)  NOT NULL,
    ROLE               VARCHAR2(10)  NOT NULL,
    STATUS             VARCHAR2(10)  DEFAULT 'ACTIVO' NOT NULL,
    REGISTRATION_DATE  DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_USERS PRIMARY KEY (ID),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USERS_ROLE CHECK (ROLE IN ('ADMIN', 'CLIENTE')),
    CONSTRAINT CK_USERS_STATUS CHECK (STATUS IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE DEPARTMENTS (
    ID    NUMBER GENERATED ALWAYS AS IDENTITY,
    NAME  VARCHAR2(60) NOT NULL,
    CONSTRAINT PK_DEPARTMENTS PRIMARY KEY (ID)
);

CREATE TABLE MUNICIPALITIES (
    ID             NUMBER GENERATED ALWAYS AS IDENTITY,
    DEPARTMENT_ID  NUMBER NOT NULL,
    NAME           VARCHAR2(60) NOT NULL,
    CONSTRAINT PK_MUNICIPALITIES PRIMARY KEY (ID),
    CONSTRAINT FK_MUNICIPALITIES_DEPT FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENTS (ID)
);

CREATE TABLE NEIGHBORHOODS (
    ID               NUMBER GENERATED ALWAYS AS IDENTITY,
    MUNICIPALITY_ID  NUMBER NOT NULL,
    NAME             VARCHAR2(60) NOT NULL,
    CONSTRAINT PK_NEIGHBORHOODS PRIMARY KEY (ID),
    CONSTRAINT FK_NEIGHBORHOODS_MUNI FOREIGN KEY (MUNICIPALITY_ID) REFERENCES MUNICIPALITIES (ID)
);

CREATE TABLE USER_ADDRESSES (
    ID               NUMBER GENERATED ALWAYS AS IDENTITY,
    USER_ID          NUMBER NOT NULL,
    NEIGHBORHOOD_ID  NUMBER NOT NULL,
    ADDRESS          VARCHAR2(200) NOT NULL,
    IS_MAIN          CHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_USER_ADDRESSES PRIMARY KEY (ID),
    CONSTRAINT FK_USER_ADDRESSES_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    CONSTRAINT FK_USER_ADDRESSES_NEIGH FOREIGN KEY (NEIGHBORHOOD_ID) REFERENCES NEIGHBORHOODS (ID),
    CONSTRAINT CK_USER_ADDRESSES_MAIN CHECK (IS_MAIN IN ('S', 'N'))
);

-- ---------------------------------------------------------------------
-- 3. Socios (proveedores y talleres) y sus servicios
-- ---------------------------------------------------------------------
CREATE TABLE PARTNERS (
    ID                 NUMBER GENERATED ALWAYS AS IDENTITY,
    PARTNER_TYPE       VARCHAR2(10)  NOT NULL,
    COMPANY_NAME       VARCHAR2(120) NOT NULL,
    TAX_ID             VARCHAR2(20)  NOT NULL,
    PHONE              VARCHAR2(15)  NOT NULL,
    STATUS             VARCHAR2(10)  DEFAULT 'ACTIVO' NOT NULL,
    REGISTRATION_DATE  DATE          DEFAULT SYSDATE NOT NULL,
    ADDRESS            VARCHAR2(200),
    LATITUDE           NUMBER(9,6),
    LONGITUDE          NUMBER(9,6),
    CONSTRAINT PK_PARTNERS PRIMARY KEY (ID),
    CONSTRAINT UQ_PARTNERS_TAX_ID UNIQUE (TAX_ID),
    CONSTRAINT CK_PARTNERS_TYPE CHECK (PARTNER_TYPE IN ('PROVEEDOR', 'TALLER')),
    CONSTRAINT CK_PARTNERS_STATUS CHECK (STATUS IN ('ACTIVO', 'INACTIVO')),
    CONSTRAINT CK_PARTNERS_LATITUDE CHECK (LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CK_PARTNERS_LONGITUDE CHECK (LONGITUDE BETWEEN -180 AND 180)
);

CREATE TABLE SUPPLIERS (
    PARTNER_ID     NUMBER NOT NULL,
    DELIVERY_DAYS  NUMBER(3) NOT NULL,
    CONSTRAINT PK_SUPPLIERS PRIMARY KEY (PARTNER_ID),
    CONSTRAINT FK_SUPPLIERS_PARTNER FOREIGN KEY (PARTNER_ID) REFERENCES PARTNERS (ID),
    CONSTRAINT CK_SUPPLIERS_DAYS CHECK (DELIVERY_DAYS >= 0)
);

CREATE TABLE WORKSHOPS (
    PARTNER_ID  NUMBER NOT NULL,
    SPECIALTY   VARCHAR2(80) NOT NULL,
    BAY_COUNT   NUMBER(3) NOT NULL,
    CONSTRAINT PK_WORKSHOPS PRIMARY KEY (PARTNER_ID),
    CONSTRAINT FK_WORKSHOPS_PARTNER FOREIGN KEY (PARTNER_ID) REFERENCES PARTNERS (ID),
    CONSTRAINT CK_WORKSHOPS_BAYS CHECK (BAY_COUNT >= 0)
);

CREATE TABLE SERVICES (
    ID           NUMBER GENERATED ALWAYS AS IDENTITY,
    WORKSHOP_ID  NUMBER NOT NULL,
    NAME         VARCHAR2(100) NOT NULL,
    DESCRIPTION  VARCHAR2(300),
    STATUS       VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_SERVICES PRIMARY KEY (ID),
    CONSTRAINT FK_SERVICES_WORKSHOP FOREIGN KEY (WORKSHOP_ID) REFERENCES WORKSHOPS (PARTNER_ID),
    CONSTRAINT CK_SERVICES_STATUS CHECK (STATUS IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE FEES (
    ID          NUMBER GENERATED ALWAYS AS IDENTITY,
    SERVICE_ID  NUMBER NOT NULL,
    AMOUNT      NUMBER(12) NOT NULL,
    START_DATE  DATE NOT NULL,
    STATUS      VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_FEES PRIMARY KEY (ID),
    CONSTRAINT FK_FEES_SERVICE FOREIGN KEY (SERVICE_ID) REFERENCES SERVICES (ID),
    CONSTRAINT CK_FEES_AMOUNT CHECK (AMOUNT >= 0),
    CONSTRAINT CK_FEES_STATUS CHECK (STATUS IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE AFFILIATIONS (
    ID           NUMBER GENERATED ALWAYS AS IDENTITY,
    SUPPLIER_ID  NUMBER NOT NULL,
    WORKSHOP_ID  NUMBER NOT NULL,
    START_DATE   DATE NOT NULL,
    STATUS       VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_AFFILIATIONS PRIMARY KEY (ID),
    CONSTRAINT FK_AFFILIATIONS_SUPPLIER FOREIGN KEY (SUPPLIER_ID) REFERENCES SUPPLIERS (PARTNER_ID),
    CONSTRAINT FK_AFFILIATIONS_WORKSHOP FOREIGN KEY (WORKSHOP_ID) REFERENCES WORKSHOPS (PARTNER_ID),
    CONSTRAINT CK_AFFILIATIONS_STATUS CHECK (STATUS IN ('ACTIVO', 'INACTIVO'))
);

-- ---------------------------------------------------------------------
-- 4. Componentes (repuestos) y sus subtipos
--    Los repuestos no se borran: se pasan a INACTIVO.
-- ---------------------------------------------------------------------
CREATE TABLE COMPONENTS (
    ID              NUMBER GENERATED ALWAYS AS IDENTITY,
    COMPONENT_TYPE  VARCHAR2(12)  DEFAULT 'GENERAL' NOT NULL,
    NAME            VARCHAR2(120) NOT NULL,
    REFERENCE       VARCHAR2(40)  NOT NULL,
    BRAND_ID        NUMBER NOT NULL,
    CATEGORY_ID     NUMBER NOT NULL,
    ORIGIN          VARCHAR2(10)  NOT NULL,
    DESCRIPTION     VARCHAR2(300),
    STATUS          VARCHAR2(10)  DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_COMPONENTS PRIMARY KEY (ID),
    CONSTRAINT UQ_COMPONENTS_REFERENCE UNIQUE (REFERENCE),
    CONSTRAINT FK_COMPONENTS_BRAND FOREIGN KEY (BRAND_ID) REFERENCES BRANDS (ID),
    CONSTRAINT FK_COMPONENTS_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES (ID),
    CONSTRAINT CK_COMPONENTS_TYPE CHECK (COMPONENT_TYPE IN ('GENERAL', 'LLANTA', 'RIN', 'MOTOR', 'TRANSMISION')),
    CONSTRAINT CK_COMPONENTS_ORIGIN CHECK (ORIGIN IN ('ORIGINAL', 'GENERICO')),
    CONSTRAINT CK_COMPONENTS_STATUS CHECK (STATUS IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE TIRES (
    COMPONENT_ID     NUMBER NOT NULL,
    WIDTH_MM         NUMBER(4) NOT NULL,
    ASPECT_RATIO     NUMBER(3) NOT NULL,
    DIAMETER_INCHES  NUMBER(3) NOT NULL,
    LOAD_INDEX       NUMBER(3) NOT NULL,
    SPEED_INDEX      VARCHAR2(2) NOT NULL,
    CONSTRAINT PK_TIRES PRIMARY KEY (COMPONENT_ID),
    CONSTRAINT FK_TIRES_COMPONENT FOREIGN KEY (COMPONENT_ID) REFERENCES COMPONENTS (ID)
);

CREATE TABLE RIMS (
    COMPONENT_ID     NUMBER NOT NULL,
    DIAMETER_INCHES  NUMBER(4,1) NOT NULL,
    WIDTH_INCHES     NUMBER(4,1) NOT NULL,
    PCD              VARCHAR2(20) NOT NULL,
    MATERIAL         VARCHAR2(10) NOT NULL,
    CONSTRAINT PK_RIMS PRIMARY KEY (COMPONENT_ID),
    CONSTRAINT FK_RIMS_COMPONENT FOREIGN KEY (COMPONENT_ID) REFERENCES COMPONENTS (ID),
    CONSTRAINT CK_RIMS_MATERIAL CHECK (MATERIAL IN ('ALEACION', 'ACERO'))
);

CREATE TABLE ENGINES (
    COMPONENT_ID     NUMBER NOT NULL,
    DISPLACEMENT_CC  NUMBER(5) NOT NULL,
    CYLINDERS        NUMBER(2) NOT NULL,
    FUEL             VARCHAR2(10) NOT NULL,
    HORSEPOWER       NUMBER(4) NOT NULL,
    CONSTRAINT PK_ENGINES PRIMARY KEY (COMPONENT_ID),
    CONSTRAINT FK_ENGINES_COMPONENT FOREIGN KEY (COMPONENT_ID) REFERENCES COMPONENTS (ID),
    CONSTRAINT CK_ENGINES_FUEL CHECK (FUEL IN ('GASOLINA', 'DIESEL'))
);

CREATE TABLE TRANSMISSIONS (
    COMPONENT_ID       NUMBER NOT NULL,
    TRANSMISSION_TYPE  VARCHAR2(12) NOT NULL,
    NUMBER_OF_SPEEDS   NUMBER(2) NOT NULL,
    CONSTRAINT PK_TRANSMISSIONS PRIMARY KEY (COMPONENT_ID),
    CONSTRAINT FK_TRANSMISSIONS_COMPONENT FOREIGN KEY (COMPONENT_ID) REFERENCES COMPONENTS (ID),
    CONSTRAINT CK_TRANSMISSIONS_TYPE CHECK (TRANSMISSION_TYPE IN ('MANUAL', 'AUTOMATICA'))
);

-- Fotos del repuesto. En disco solo se guarda el nombre (images/components/).
CREATE TABLE COMPONENT_IMAGES (
    ID            NUMBER GENERATED ALWAYS AS IDENTITY,
    COMPONENT_ID  NUMBER NOT NULL,
    FILE_NAME     VARCHAR2(120) NOT NULL,
    IS_MAIN       CHAR(1) DEFAULT 'N' NOT NULL,
    SORT_ORDER    NUMBER(3) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_COMPONENT_IMAGES PRIMARY KEY (ID),
    CONSTRAINT FK_COMPONENT_IMAGES_COMP FOREIGN KEY (COMPONENT_ID) REFERENCES COMPONENTS (ID),
    CONSTRAINT CK_COMPONENT_IMAGES_MAIN CHECK (IS_MAIN IN ('S', 'N'))
);

-- ---------------------------------------------------------------------
-- 5. Vehículos y compatibilidad
--    BRAND_NAME es texto: BRANDS tiene las marcas de repuestos (Bosch,
--    Brembo...), no las de vehículos (Chevrolet, Toyota...). Así viene
--    también en vehicles.csv.
-- ---------------------------------------------------------------------
CREATE TABLE VEHICLES (
    ID            NUMBER GENERATED ALWAYS AS IDENTITY,
    VEHICLE_TYPE  VARCHAR2(12) NOT NULL,
    BRAND_NAME    VARCHAR2(60) NOT NULL,
    MODEL_NAME    VARCHAR2(80) NOT NULL,
    YEAR_RELEASE  NUMBER(4) NOT NULL,
    STATUS        VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_VEHICLES PRIMARY KEY (ID),
    CONSTRAINT CK_VEHICLES_TYPE CHECK (VEHICLE_TYPE IN ('COCHE', 'MOTOCICLETA')),
    CONSTRAINT CK_VEHICLES_YEAR CHECK (YEAR_RELEASE BETWEEN 1900 AND 2100),
    CONSTRAINT CK_VEHICLES_STATUS CHECK (STATUS IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE CARS (
    VEHICLE_ID  NUMBER NOT NULL,
    NUM_DOORS   NUMBER(2) NOT NULL,
    CAR_TYPE    VARCHAR2(12) NOT NULL,
    CONSTRAINT PK_CARS PRIMARY KEY (VEHICLE_ID),
    CONSTRAINT FK_CARS_VEHICLE FOREIGN KEY (VEHICLE_ID) REFERENCES VEHICLES (ID),
    CONSTRAINT CK_CARS_TYPE CHECK (CAR_TYPE IN ('CAMIONETA', 'HATCHBACK', 'SEDAN', 'DEPORTIVO'))
);

CREATE TABLE MOTORCYCLES (
    VEHICLE_ID       NUMBER NOT NULL,
    DISPLACEMENT_CC  NUMBER(5) NOT NULL,
    MOTORCYCLE_TYPE  VARCHAR2(12) NOT NULL,
    CONSTRAINT PK_MOTORCYCLES PRIMARY KEY (VEHICLE_ID),
    CONSTRAINT FK_MOTORCYCLES_VEHICLE FOREIGN KEY (VEHICLE_ID) REFERENCES VEHICLES (ID),
    CONSTRAINT CK_MOTORCYCLES_TYPE CHECK (MOTORCYCLE_TYPE IN ('SCOOTER', 'NAKED', 'DEPORTIVAS'))
);

CREATE TABLE COMPATIBILITY (
    COMPONENT_ID  NUMBER NOT NULL,
    VEHICLE_ID    NUMBER NOT NULL,
    CONSTRAINT PK_COMPATIBILITY PRIMARY KEY (COMPONENT_ID, VEHICLE_ID),
    CONSTRAINT FK_COMPATIBILITY_COMPONENT FOREIGN KEY (COMPONENT_ID) REFERENCES COMPONENTS (ID),
    CONSTRAINT FK_COMPATIBILITY_VEHICLE FOREIGN KEY (VEHICLE_ID) REFERENCES VEHICLES (ID)
);

-- ---------------------------------------------------------------------
-- 6. Inventario (oferta de un proveedor por un componente)
--    No hay UNIQUE (proveedor, componente): una oferta desactivada sigue en
--    la tabla y se puede crear otra igual. InventoryService cuida que no haya
--    dos ofertas ACTIVAS repetidas.
-- ---------------------------------------------------------------------
CREATE TABLE INVENTORY (
    ID               NUMBER GENERATED ALWAYS AS IDENTITY,
    SUPPLIER_ID      NUMBER NOT NULL,
    COMPONENT_ID     NUMBER NOT NULL,
    PRICE            NUMBER(12) NOT NULL,
    STOCK            NUMBER(6) DEFAULT 0 NOT NULL,
    SHIPPING_COST    NUMBER(10) DEFAULT 0 NOT NULL,
    WARRANTY_MONTHS  NUMBER(3) DEFAULT 0 NOT NULL,
    CONDITION        VARCHAR2(15) DEFAULT 'NUEVO' NOT NULL,
    DESCRIPTION      VARCHAR2(500),
    STATUS           VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_INVENTORY PRIMARY KEY (ID),
    CONSTRAINT FK_INVENTORY_SUPPLIER FOREIGN KEY (SUPPLIER_ID) REFERENCES SUPPLIERS (PARTNER_ID),
    CONSTRAINT FK_INVENTORY_COMPONENT FOREIGN KEY (COMPONENT_ID) REFERENCES COMPONENTS (ID),
    CONSTRAINT CK_INVENTORY_PRICE CHECK (PRICE > 0),
    CONSTRAINT CK_INVENTORY_STOCK CHECK (STOCK >= 0),
    CONSTRAINT CK_INVENTORY_SHIPPING CHECK (SHIPPING_COST >= 0),
    CONSTRAINT CK_INVENTORY_WARRANTY CHECK (WARRANTY_MONTHS >= 0),
    CONSTRAINT CK_INVENTORY_CONDITION CHECK (CONDITION IN ('NUEVO', 'USADO', 'REACONDICIONADO')),
    CONSTRAINT CK_INVENTORY_STATUS CHECK (STATUS IN ('ACTIVO', 'INACTIVO'))
);

-- Fotos de cada oferta. La foto y la descripción de la tienda (accesorios,
-- estado real) van aquí y en INVENTORY.DESCRIPTION, no en el componente:
-- el componente es el producto del catálogo y es el mismo para todas las
-- tiendas. COMPONENT_IMAGES sigue siendo la foto general del producto (la de
-- la tarjeta del catálogo y la que se usa si la tienda no subió fotos).
-- En disco solo se guarda el nombre del archivo (images/inventory/).
CREATE TABLE INVENTORY_IMAGES (
    ID            NUMBER GENERATED ALWAYS AS IDENTITY,
    INVENTORY_ID  NUMBER NOT NULL,
    FILE_NAME     VARCHAR2(120) NOT NULL,
    CAPTION       VARCHAR2(120),
    IS_MAIN       CHAR(1) DEFAULT 'N' NOT NULL,
    SORT_ORDER    NUMBER(3) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_INVENTORY_IMAGES PRIMARY KEY (ID),
    CONSTRAINT FK_INVENTORY_IMAGES_INV FOREIGN KEY (INVENTORY_ID) REFERENCES INVENTORY (ID),
    CONSTRAINT CK_INVENTORY_IMAGES_MAIN CHECK (IS_MAIN IN ('S', 'N'))
);

-- ---------------------------------------------------------------------
-- 7. Pedidos (carrito confirmado) e historial de precios
--    El stock se descuenta con un disparador sobre ORDER_ITEMS y el
--    historial lo llena otro disparador sobre INVENTORY (03_disparadores.sql).
-- ---------------------------------------------------------------------
CREATE TABLE ORDERS (
    ID          NUMBER GENERATED ALWAYS AS IDENTITY,
    USER_ID     NUMBER NOT NULL,
    ORDER_DATE  DATE DEFAULT SYSDATE NOT NULL,
    STATUS      VARCHAR2(12) DEFAULT 'PENDIENTE' NOT NULL,
    TOTAL       NUMBER(14) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ORDERS PRIMARY KEY (ID),
    CONSTRAINT FK_ORDERS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    CONSTRAINT CK_ORDERS_STATUS CHECK (STATUS IN ('PENDIENTE', 'CONFIRMADO', 'CANCELADO')),
    CONSTRAINT CK_ORDERS_TOTAL CHECK (TOTAL >= 0)
);

CREATE TABLE ORDER_ITEMS (
    ID             NUMBER GENERATED ALWAYS AS IDENTITY,
    ORDER_ID       NUMBER NOT NULL,
    INVENTORY_ID   NUMBER NOT NULL,
    QUANTITY       NUMBER(4) NOT NULL,
    UNIT_PRICE     NUMBER(12) NOT NULL,
    SHIPPING_COST  NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ORDER_ITEMS PRIMARY KEY (ID),
    CONSTRAINT FK_ORDER_ITEMS_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS (ID),
    CONSTRAINT FK_ORDER_ITEMS_INVENTORY FOREIGN KEY (INVENTORY_ID) REFERENCES INVENTORY (ID),
    CONSTRAINT CK_ORDER_ITEMS_QTY CHECK (QUANTITY > 0),
    CONSTRAINT CK_ORDER_ITEMS_PRICE CHECK (UNIT_PRICE > 0),
    CONSTRAINT CK_ORDER_ITEMS_SHIPPING CHECK (SHIPPING_COST >= 0)
);

CREATE TABLE PRICE_HISTORY (
    ID            NUMBER GENERATED ALWAYS AS IDENTITY,
    INVENTORY_ID  NUMBER NOT NULL,
    OLD_PRICE     NUMBER(12) NOT NULL,
    NEW_PRICE     NUMBER(12) NOT NULL,
    CHANGE_DATE   DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_PRICE_HISTORY PRIMARY KEY (ID),
    CONSTRAINT FK_PRICE_HISTORY_INVENTORY FOREIGN KEY (INVENTORY_ID) REFERENCES INVENTORY (ID)
);

-- ---------------------------------------------------------------------
