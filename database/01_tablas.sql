-- Se puede correr varias veces: primero borra las tablas de ORIGEN y las
-- vuelve a crear (los datos se cargan después con 02_datos.sql).
--
-- Herencia: se usa UNA TABLA POR SUBCLASE. La tabla padre guarda lo común
-- y tiene una columna de tipo; cada subtabla usa como llave primaria la
-- llave foránea a su padre (relación 1 a 1).
--   COMPONENTS -> TIRES, RIMS, ENGINES, TRANSMISSIONS
--   PARTNERS   -> SUPPLIERS, WORKSHOPS
--   VEHICLES   -> CARS, MOTORCYCLES
-- Un componente de tipo GENERAL no tiene fila en ninguna subtabla.
--
-- Los valores de texto (estados, roles, tipos) son los mismos que se
-- guardan hoy en los archivos .csv, así los DAO de Oracle no traducen nada.
-- =====================================================================

